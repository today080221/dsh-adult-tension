import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const integration = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(integration, '../..');
const scratch = await fs.mkdtemp(path.join(os.tmpdir(), 'adult-tension-st-qa-'));
await fs.cp(path.join(integration, 'deployment'), scratch, { recursive: true });
await fs.writeFile(path.join(scratch, 'package.json'), '{"type":"module"}', 'utf8');
const runtime = path.join(scratch, 'data/adult-tension');
await fs.mkdir(path.join(runtime, 'evidence'), { recursive: true });
await fs.cp(path.join(repo, 'skill/adult-tension'), path.join(runtime, 'upstream/skill/adult-tension'), { recursive: true });
await fs.mkdir(path.join(runtime, 'upstream/content-src/examples'), { recursive: true });
await fs.copyFile(path.join(repo, 'content-src/examples/custom_world.json'), path.join(runtime, 'upstream/content-src/examples/custom_world.json'));
await fs.copyFile(path.join(integration, 'tests/integration.mjs'), path.join(runtime, 'integration.mjs'));
const result = spawnSync(process.execPath, [path.join(runtime, 'integration.mjs')], { stdio: 'inherit', windowsHide: true });
console.log('Isolated test evidence: ' + scratch);
if (result.error) throw result.error;
process.exitCode = result.status ?? 1;
